/**
 * Renders WRITING_GUIDE, the text that docs-mcp serves as guidance topic `sequence-writing`, and writes it to
 * writing-guide.ts. The guide is the whole v1 grammar page (`docs/10-language/doc.json`), then the
 * "Core architecture decisions" section of `STATE.md`. The package ships only src, so the text ships as a constant.
 *
 *   bun run writing-guide:write   regenerate src/language/writing-guide.ts
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { markdownSection, renderDocPage, type DocPage } from "./index";

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../../../..");
export const WRITING_GUIDE_FILE = join(REPO_ROOT, "packages/sequence/src/language/writing-guide.ts");

/** The guide text from the grammar page and STATE.md of `repoRoot`. */
export async function renderWritingGuide(repoRoot: string = REPO_ROOT): Promise<string> {
  const page = JSON.parse(await readFile(join(repoRoot, "docs/10-language/doc.json"), "utf8")) as DocPage;
  const decisions = markdownSection(await readFile(join(repoRoot, "STATE.md"), "utf8"), "Core architecture decisions");
  return `${renderDocPage(page)}\n\n# Sequence Design Decisions\n\nThese decisions are settled. Do not change them without Ford.\n\n${decisions}\n`;
}

const templateLiteral = (text: string): string => `\`${text.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${")}\``;

/** The source of writing-guide.ts for one guide text. */
export const writingGuideModule = (guide: string): string =>
  `// Generated by \`bun run writing-guide:write\` from docs/10-language/doc.json and STATE.md. Do not edit this file by hand.\n\n` +
  `/** The sequence language page and the design decisions, served by docs-mcp as guidance topic \`sequence-writing\`. */\n` +
  `export const WRITING_GUIDE = ${templateLiteral(guide)};\n`;

if (import.meta.main) {
  await writeFile(WRITING_GUIDE_FILE, writingGuideModule(await renderWritingGuide()));
  console.log(`Wrote ${relative(REPO_ROOT, WRITING_GUIDE_FILE)}.`);
}
